/** TurboQuant's rotation sign tables: writes src/kernels/turboquant/signs.ts from the
 * construction the vendored vllm-metal reference defines (`02d723a:lab/repro/
 * vllm-metal-turboquant/turboquant_reference.py`, `fwht()`): for a head dimension d,
 * `sign01 = mx.random.randint(0, 2, shape=(d,), key=mx.random.key(42))` and
 * `signs = 1 - 2 * sign01`; the rotation is those signs then MLX's
 * `hadamard_transform` (scale 1/sqrt(d)). The construction is defined for every d
 * the value layout and the transform take: a multiple of the 32-element scale
 * group that MLX's Hadamard transform accepts (m·2^k for m in {1, 12, 20, 28}).
 * The reference tabulates 64, 128, 256 and 512 because its Metal kernel hardcodes
 * those four; the codec here rotates through MLX's transform, so it takes every
 * served head dimension the construction defines. The four reference sizes are
 * regenerated bit for bit (the drift test, tests/kernels/turboquant-signs.test.ts,
 * holds the committed file to this output). `--help` loads no native library. */
import { resolve } from "node:path";
import { parseArgs } from "node:util";

export const SIGNS_FILE = resolve(import.meta.dir, "../src/kernels/turboquant/signs.ts");
/** The served head dimensions: the reference's four and the ones the families serve beyond them
 * (96: the universal family's phi3 descriptor, Phi-3 and Phi-3.5 mini). */
export const HEAD_DIMS = [64, 96, 128, 256, 512] as const;
const KEY = 42n;

const USAGE = `usage: bun packages/inference/scripts/gen-turboquant-signs.ts [--out <file>] [--dims 64,96,...]

Writes the TurboQuant rotation sign table for each head dimension (default: ${HEAD_DIMS.join(", ")})
to --out (default: src/kernels/turboquant/signs.ts). Each dimension must be a multiple of 32 that
MLX's hadamard_transform takes (m·2^k, m in {1, 12, 20, 28}). Needs the native MLX library
(MLX_BUN_LIBMLXC).`;

/** Whether the construction defines a rotation for `d`: 32-element groups and an MLX Hadamard size. */
export function definedHeadDim(d: number): boolean {
  if (!Number.isInteger(d) || d <= 0 || d % 32 !== 0) return false;
  for (const m of [1, 12, 20, 28]) {
    if (d % m !== 0) continue;
    const power = d / m;
    if ((power & (power - 1)) === 0) return true;
  }
  return false;
}

/** The ±1 signs of the reference's `fwht()` for head dimension `d`. */
export async function signVector(d: number): Promise<number[]> {
  const ops = await import("@mlx-bun/mlx/ops");
  const { Dtype } = await import("@mlx-bun/mlx/ffi");
  using key = ops.randomKey(KEY);
  using bits = ops.randint(0, 2, [d], Dtype.int32, key);
  return bits.toIntTokens().map(bit => 1 - 2 * bit);
}

/** The generated module for `dims`. */
export async function render(dims: readonly number[]): Promise<string> {
  const rows = (values: number[]) => {
    const lines: string[] = [];
    for (let i = 0; i < values.length; i += 10) lines.push(`  ${values.slice(i, i + 10).join(", ")},`);
    return lines.join("\n");
  };
  const tables: string[] = [];
  for (const d of dims) tables.push(`  ${d}: [\n${rows(await signVector(d))}\n  ],`);
  return `// GENERATED by packages/inference/scripts/gen-turboquant-signs.ts; do not edit.
//
// TurboQuant's rotation signs per head dimension, from the construction the
// vendored vllm-metal reference defines (\`02d723a:lab/repro/vllm-metal-turboquant/
// turboquant_reference.py\`, \`fwht()\`): randint(0, 2, shape=(d,), key=key(42)),
// mapped to 1 - 2·bit. The rotation is these signs then MLX's hadamard_transform.

export const TURBOQUANT_HEAD_DIMS = [${dims.join(", ")}] as const;
export type TurboQuantHeadDim = (typeof TURBOQUANT_HEAD_DIMS)[number];

export const SIGN_VECTORS: Record<TurboQuantHeadDim, number[]> = {
${tables.join("\n")}
};
`;
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { help: { type: "boolean", short: "h" }, out: { type: "string" }, dims: { type: "string" } } });
  if (values.help) { console.log(USAGE); process.exit(0); }
  const dims = values.dims ? values.dims.split(",").map(Number) : [...HEAD_DIMS];
  const undefinedDims = dims.filter(d => !definedHeadDim(d));
  if (undefinedDims.length) {
    console.error(`the construction defines no rotation for head dimension ${undefinedDims.join(", ")}\n${USAGE}`);
    process.exit(1);
  }
  const out = values.out ? resolve(values.out) : SIGNS_FILE;
  await Bun.write(out, await render([...dims].sort((a, b) => a - b)));
  console.log(`gen-turboquant-signs: wrote ${dims.length} sign tables to ${out}`);
}
